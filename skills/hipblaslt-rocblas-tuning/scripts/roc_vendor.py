#!/usr/bin/env python3
"""Adapter for the NMZ rocblas-autotune framework. Not a generic upstream ROCm API."""
import argparse
import hashlib
import inspect
import os
from pathlib import Path
import shutil
import sys
from gemm_plan import checked_plan, roc_input, save
from identity import check, sha
from tune_hip import clean_env


def tree_sha(root):
    h = hashlib.sha256()
    for file in sorted(root.rglob('*')):
        if file.is_file() and '__pycache__' not in file.parts:
            h.update(str(file.relative_to(root)).encode()); h.update(sha(file).encode())
    return h.hexdigest()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('mode', choices=['prepare', 'tune', 'generate'])
    p.add_argument('--plan', required=True); p.add_argument('--work', required=True)
    p.add_argument('--source', help='external, version-matched rocblas-autotune source tree; prepare only')
    p.add_argument('--vendor-config', help='reviewed tuning_args.txt; prepare only')
    p.add_argument('--runtime-root', help='e.g. /opt/dtk/lib/rocblas; tune only')
    p.add_argument('--native-library', help='actual current library_gpu6 path; tune/generate')
    a = p.parse_args()
    plan = checked_plan(a.plan); check(plan['identity'])
    work = Path(a.work).resolve()
    if a.mode == 'prepare':
        if not a.source or not a.vendor_config:
            p.error('prepare needs --source and --vendor-config')
        work.mkdir(parents=True, exist_ok=False)
        for directory in ('src', 'source-all', 'source-test', 'source-quick', 'configs'):
            shutil.copytree(Path(a.source) / directory, work / directory)
        shutil.copy2(a.vendor_config, work / 'configs/tuning_args.txt')
        target = work / 'csv_size/csv'; target.mkdir(parents=True)
        roc_input(plan, target / 'captured-powers.csv')
        save(work / 'skill-provenance.json', {'plan_fingerprint': plan['fingerprint'], 'source': str(Path(a.source).resolve()), 'source_sha256': tree_sha(work / 'src'), 'config_sha256': sha(work / 'configs/tuning_args.txt')})
        return
    import json
    provenance = json.loads((work / 'skill-provenance.json').read_text())
    if provenance['plan_fingerprint'] != plan['fingerprint'] or provenance['source_sha256'] != tree_sha(work / 'src') or provenance['config_sha256'] != sha(work / 'configs/tuning_args.txt'):
        raise ValueError('plan, vendor source or tuning config drift')
    if not a.native_library:
        p.error('tune/generate needs --native-library')
    if a.mode == 'tune' and not a.runtime_root:
        p.error('tune needs --runtime-root')
    cleaned_environment = clean_env()
    os.environ.clear(); os.environ.update(cleaned_environment)
    sys.path.insert(0, str(work)); os.chdir(work)
    from src.apps.tuning_app import GemmTunerApp
    from src.settings.config import get_config
    from src.settings.constants import ConfigMappings
    for name in ('_prepare_configs', '_extract_sizes', '_run_tuning', '_generate_configs'):
        if not hasattr(GemmTunerApp, name):
            raise RuntimeError(f'incompatible vendor framework: {name}')
    if 'is_final' not in inspect.signature(GemmTunerApp._generate_configs).parameters:
        raise RuntimeError('incompatible vendor config generator signature')
    if a.mode == 'tune':
        if (work / 'skill-tuned.json').exists():
            raise ValueError('fresh isolated work directory required; no implicit resume')
        app = GemmTunerApp(str(work / 'configs/tuning_args.txt'))
        app._prepare_configs(a.runtime_root)
        result = app._extract_sizes(); app._run_tuning(result, a.runtime_root)
        app._generate_configs(result, is_final=False)
        save(work / 'skill-tuned.json', {'plan_fingerprint': plan['fingerprint']})
    else:
        if not (work / 'skill-tuned.json').exists():
            raise ValueError('missing completed powers tuning')
        # Avoid constructor: it may clean/recompile and discard filled results.
        app = GemmTunerApp.__new__(GemmTunerApp)
        app.config = get_config(str(work / 'configs/tuning_args.txt'))
        app.config_subdir = ConfigMappings.get_library_dir('NMZ')
        app.package_dir = str(work)
        app._generate_configs(app._extract_sizes(), is_final=False)
    target = work / 'optimization_configs/new/config/library_gpu6'
    if not target.is_dir():
        raise ValueError('generator did not create expected NMZ native directory')
    # Supply unchanged binaries/maps not generated by the tuner; never overwrite system files.
    for file in Path(a.native_library).iterdir():
        destination = target / file.name
        if not destination.exists():
            if file.is_dir():
                shutil.copytree(file, destination)
            else:
                shutil.copy2(file, destination)
    check(plan['identity'])
    save(work / ('skill-' + a.mode + '-native.json'), {'plan_fingerprint': plan['fingerprint'], 'library': str(target), 'native_source': str(Path(a.native_library).resolve()), 'tree_sha256': tree_sha(target), 'results_csv_sha256': {p.name: sha(p) for p in (work / 'optimization_artifacts/custom/results/csv').glob('*.csv')}})
    print(target)


if __name__ == '__main__':
    main()
